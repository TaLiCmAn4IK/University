-- Заданий 1 и 2
SELECT 
    В.Наименование_операции AS [Наименование операции],
    MAX(В.Количество_деталей) AS [Максимальное количество деталей],
    MIN(В.Количество_деталей) AS [Минимальное количество деталей],
    AVG(CAST(В.Количество_деталей AS FLOAT)) AS [Среднее количество деталей],
    SUM(В.Количество_деталей) AS [Суммарное количество деталей],
    COUNT(*) AS [Количество выполнений]
FROM ВЫПОЛНЕНИЕ В
INNER JOIN ОПЕРАЦИИ О ON В.Наименование_операции = О.Наименование_операции
GROUP BY В.Наименование_операции;
GO

-- Задания 3
SELECT *
FROM (
    SELECT 
        CASE 
            WHEN Количество_деталей BETWEEN 1 AND 5 THEN '1-5 деталей'
            WHEN Количество_деталей BETWEEN 6 AND 10 THEN '6-10 деталей'
            WHEN Количество_деталей BETWEEN 11 AND 15 THEN '11-15 деталей'
            WHEN Количество_деталей BETWEEN 16 AND 20 THEN '16-20 деталей'
            ELSE 'Более 20 деталей'
        END AS [Интервал количества деталей],
        COUNT(*) AS [Количество выполнений]
    FROM ВЫПОЛНЕНИЕ
    GROUP BY 
        CASE 
            WHEN Количество_деталей BETWEEN 1 AND 5 THEN '1-5 деталей'
            WHEN Количество_деталей BETWEEN 6 AND 10 THEN '6-10 деталей'
            WHEN Количество_деталей BETWEEN 11 AND 15 THEN '11-15 деталей'
            WHEN Количество_деталей BETWEEN 16 AND 20 THEN '16-20 деталей'
            ELSE 'Более 20 деталей'
        END
) AS T
ORDER BY 
    CASE [Интервал количества деталей]
        WHEN '1-5 деталей' THEN 1
        WHEN '6-10 деталей' THEN 2
        WHEN '11-15 деталей' THEN 3
        WHEN '16-20 деталей' THEN 4
        ELSE 5
    END;
GO

-- Задания 4
SELECT 
    Р.Фамилия + ' ' + Р.Имя AS [Работник],
    О.Признак_сложности AS [Сложность операций],
    CAST(ROUND(AVG(CAST(В.Количество_деталей AS FLOAT)), 2) AS DECIMAL(5,2)) AS [Среднее количество деталей]
FROM РАБОТНИКИ Р
INNER JOIN ВЫПОЛНЕНИЕ В ON Р.ID_работника = В.ID_работника
INNER JOIN ОПЕРАЦИИ О ON В.Наименование_операции = О.Наименование_операции
GROUP BY Р.Фамилия, Р.Имя, О.Признак_сложности
ORDER BY [Среднее количество деталей] DESC;
GO

-- Задания 5
SELECT 
    Р.Фамилия + ' ' + Р.Имя AS [Работник],
    О.Признак_сложности AS [Сложность операций],
    CAST(ROUND(AVG(CAST(В.Количество_деталей AS FLOAT)), 2) AS DECIMAL(5,2)) AS [Среднее количество деталей]
FROM РАБОТНИКИ Р
INNER JOIN ВЫПОЛНЕНИЕ В ON Р.ID_работника = В.ID_работника
INNER JOIN ОПЕРАЦИИ О ON В.Наименование_операции = О.Наименование_операции
WHERE О.Признак_сложности = 'Высокая'
GROUP BY Р.Фамилия, Р.Имя, О.Признак_сложности
ORDER BY [Среднее количество деталей] DESC;
GO

-- Задания 6
SELECT 
    В.Наименование_операции AS [Операция],
    Р.Фамилия + ' ' + Р.Имя AS [Работник],
    CAST(ROUND(AVG(CAST(В.Количество_деталей AS FLOAT)), 2) AS DECIMAL(5,2)) AS [Среднее количество деталей]
FROM ВЫПОЛНЕНИЕ В
INNER JOIN РАБОТНИКИ Р ON В.ID_работника = Р.ID_работника
WHERE В.Наименование_операции = 'Сварка'
GROUP BY В.Наименование_операции, Р.Фамилия, Р.Имя
ORDER BY Р.Фамилия, [Среднее количество деталей] DESC;
GO

-- Задания 7
SELECT 
    В.Наименование_операции AS [Операция],
    В.Количество_деталей AS [Количество деталей],
    COUNT(*) AS [Количество выполнений]
FROM ВЫПОЛНЕНИЕ В
GROUP BY В.Наименование_операции, В.Количество_деталей
HAVING В.Количество_деталей IN (8, 9)
ORDER BY В.Наименование_операции, В.Количество_деталей DESC;
GO
