SELECT *
FROM (
    SELECT 
        CASE 
            WHEN NOTE BETWEEN 1 AND 3 THEN 'Оценка 1-3'
            WHEN NOTE BETWEEN 4 AND 6 THEN 'Оценка 4-6'
            WHEN NOTE BETWEEN 7 AND 8 THEN 'Оценка 7-8'
            WHEN NOTE BETWEEN 9 AND 10 THEN 'Оценка 9-10'
            ELSE 'Другое'
        END AS [Интервал оценок],
        COUNT(*) AS [Количество]
    FROM PROGRESS
    GROUP BY 
        CASE 
            WHEN NOTE BETWEEN 1 AND 3 THEN 'Оценка 1-3'
            WHEN NOTE BETWEEN 4 AND 6 THEN 'Оценка 4-6'
            WHEN NOTE BETWEEN 7 AND 8 THEN 'Оценка 7-8'
            WHEN NOTE BETWEEN 9 AND 10 THEN 'Оценка 9-10'
            ELSE 'Другое'
        END
) AS T
ORDER BY 
    CASE [Интервал оценок]
        WHEN 'Оценка 9-10' THEN 1
        WHEN 'Оценка 7-8' THEN 2
        WHEN 'Оценка 4-6' THEN 3
        WHEN 'Оценка 1-3' THEN 4
        ELSE 5
    END;

