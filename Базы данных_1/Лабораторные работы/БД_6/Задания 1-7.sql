SELECT 
    S.SUBJECT_NAME AS [Дисциплина],
    COUNT(*) AS [Количество]
FROM PROGRESS P
INNER JOIN SUBJECT S ON P.SUBJECT = S.SUBJECT
GROUP BY S.SUBJECT_NAME, P.NOTE
HAVING P.NOTE IN (8, 9)
ORDER BY S.SUBJECT_NAME, P.NOTE DESC;