SELECT 
    F.FACULTY_NAME AS [Факультет],
    P.PROFESSION_NAME AS [Специальность],
    G.YEAR_FIRST AS [Курс],
    CAST(ROUND(AVG(CAST(PR.NOTE AS FLOAT)), 2) AS DECIMAL(5,2)) AS [Средняя оценка]
FROM FACULTY F
INNER JOIN PROFESSION P ON F.FACULTY = P.FACULTY
INNER JOIN GROUPS G ON P.PROFESSION = G.PROFESSION
INNER JOIN STUDENT S ON G.IDGROUP = S.IDGROUP
INNER JOIN PROGRESS PR ON S.IDSTUDENT = PR.IDSTUDENT
GROUP BY F.FACULTY_NAME, P.PROFESSION_NAME, G.YEAR_FIRST
ORDER BY [Средняя оценка] DESC;

