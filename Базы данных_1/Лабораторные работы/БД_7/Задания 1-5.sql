-- Задание 1: ROLLUP для факультета ТОВ
SELECT 
    PROFESSION.PROFESSION_NAME AS [Специальность],
    SUBJECT.SUBJECT_NAME AS [Дисциплина],
    AVG(CAST(PROGRESS.NOTE AS FLOAT)) AS [Средняя оценка]
FROM FACULTY 
INNER JOIN PROFESSION ON FACULTY.FACULTY = PROFESSION.FACULTY
INNER JOIN GROUPS ON PROFESSION.PROFESSION = GROUPS.PROFESSION
INNER JOIN STUDENT ON GROUPS.IDGROUP = STUDENT.IDGROUP
INNER JOIN PROGRESS ON STUDENT.IDSTUDENT = PROGRESS.IDSTUDENT
INNER JOIN SUBJECT ON PROGRESS.SUBJECT = SUBJECT.SUBJECT
WHERE FACULTY.FACULTY = 'ТОВ'
GROUP BY ROLLUP (PROFESSION.PROFESSION_NAME, SUBJECT.SUBJECT_NAME);

