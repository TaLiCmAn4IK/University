-- Аналог задания 1: ROLLUP по операциям и работникам
SELECT 
    О.Наименование_операции AS [Операция],
    Р.Фамилия + ' ' + Р.Имя AS [Работник],
    SUM(В.Количество_деталей) AS [Всего деталей],
    AVG(CAST(В.Количество_деталей AS FLOAT)) AS [Среднее количество]
FROM ВЫПОЛНЕНИЕ В
INNER JOIN ОПЕРАЦИИ О ON В.Наименование_операции = О.Наименование_операции
INNER JOIN РАБОТНИКИ Р ON В.ID_работника = Р.ID_работника
GROUP BY ROLLUP (О.Наименование_операции, Р.Фамилия, Р.Имя);
GO

-- Аналог задания 2: CUBE
SELECT 
    О.Наименование_операции AS [Операция],
    Р.Фамилия + ' ' + Р.Имя AS [Работник],
    SUM(В.Количество_деталей) AS [Всего деталей]
FROM ВЫПОЛНЕНИЕ В
INNER JOIN ОПЕРАЦИИ О ON В.Наименование_операции = О.Наименование_операции
INNER JOIN РАБОТНИКИ Р ON В.ID_работника = Р.ID_работника
GROUP BY CUBE (О.Наименование_операции, Р.Фамилия, Р.Имя);
GO

-- Аналог задания 3: UNION для двух операций
-- Запрос для операции 'Токарная обработка'
SELECT 
    'Токарная' AS [Операция],
    Р.Фамилия AS [Работник],
    SUM(В.Количество_деталей) AS [Всего деталей]
FROM ВЫПОЛНЕНИЕ В
INNER JOIN РАБОТНИКИ Р ON В.ID_работника = Р.ID_работника
WHERE В.Наименование_операции = 'Токарная обработка'
GROUP BY Р.Фамилия

UNION

-- Запрос для операции 'Сварка'
SELECT 
    'Сварка' AS [Операция],
    Р.Фамилия AS [Работник],
    SUM(В.Количество_деталей) AS [Всего деталей]
FROM ВЫПОЛНЕНИЕ В
INNER JOIN РАБОТНИКИ Р ON В.ID_работника = Р.ID_работника
WHERE В.Наименование_операции = 'Сварка'
GROUP BY Р.Фамилия;
GO


