-- Задание 3 - SAVE TRAN
USE UNIVER;
GO
DELETE FROM AUDITORIUM WHERE AUDITORIUM = 'T12-3A';
GO

BEGIN TRY
    BEGIN TRAN;
        INSERT AUDITORIUM VALUES ('T12-3A', 'ЛК', 60, 'T12-3A');
        SAVE TRAN SAVE_POINT_1;
        BEGIN TRY
            INSERT AUDITORIUM VALUES ('T12-3A', 'ЛК', 70, 'T12-3A');
        END TRY
        BEGIN CATCH
            PRINT N'Ошибка: ' + ERROR_MESSAGE();
            ROLLBACK TRAN SAVE_POINT_1;
        END CATCH;
    COMMIT TRAN;
END TRY
BEGIN CATCH
    PRINT N'Ошибка: ' + ERROR_MESSAGE();
    IF @@TRANCOUNT > 0 ROLLBACK TRAN;
END CATCH;
GO

SELECT * FROM AUDITORIUM WHERE AUDITORIUM = 'T12-3A';
GO

