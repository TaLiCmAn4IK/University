-- Задание 4
SELECT DISTINCT
    О1.Признак_сложности AS [Сложность],
    О1.Наименование_операции AS [Операция],
    В1.Количество_деталей AS [Макс. количество деталей]
FROM ОПЕРАЦИИ О1
INNER JOIN ВЫПОЛНЕНИЕ В1 ON О1.Наименование_операции = В1.Наименование_операции
WHERE В1.Количество_деталей = (
    SELECT TOP 1 В2.Количество_деталей
    FROM ВЫПОЛНЕНИЕ В2
    INNER JOIN ОПЕРАЦИИ О2 ON В2.Наименование_операции = О2.Наименование_операции
    WHERE О2.Признак_сложности = О1.Признак_сложности
    ORDER BY В2.Количество_деталей DESC
)
ORDER BY В1.Количество_деталей DESC;
GO

