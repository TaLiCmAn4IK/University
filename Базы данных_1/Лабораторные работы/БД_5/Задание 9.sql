SELECT 
    Р.ID_работника AS [ID],
    Р.Фамилия AS [Фамилия],
    Р.Имя AS [Имя],
    Р.Отчество AS [Отчество],
    Р.Стаж AS [Стаж]
FROM РАБОТНИКИ Р
WHERE NOT EXISTS (
    SELECT 1
    FROM ВЫПОЛНЕНИЕ В
    WHERE В.ID_работника = Р.ID_работника
);
GO

