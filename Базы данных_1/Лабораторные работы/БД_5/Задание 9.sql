-- Задание 1
SELECT DISTINCT 
    О.Наименование_операции AS [Наименование операции],
    О.Признак_сложности AS [Сложность]
FROM ОПЕРАЦИИ О
WHERE О.Наименование_операции IN (
    SELECT DISTINCT В.Наименование_операции
    FROM ВЫПОЛНЕНИЕ В
    WHERE В.ID_работника IN (
        SELECT Р.ID_работника 
        FROM РАБОТНИКИ Р 
        WHERE Р.Стаж > 4
    )
);
GO

-- Задание 2
SELECT DISTINCT 
    О.Наименование_операции AS [Наименование операции],
    О.Признак_сложности AS [Сложность]
FROM ОПЕРАЦИИ О
INNER JOIN ВЫПОЛНЕНИЕ В ON О.Наименование_операции = В.Наименование_операции
INNER JOIN РАБОТНИКИ Р ON В.ID_работника = Р.ID_работника
WHERE Р.Стаж > 4;
GO

