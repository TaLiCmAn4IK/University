SELECT 
    (SELECT AVG(CAST(В.Количество_деталей AS FLOAT)) 
     FROM ВЫПОЛНЕНИЕ В 
     INNER JOIN ОПЕРАЦИИ О ON В.Наименование_операции = О.Наименование_операции
     WHERE О.Признак_сложности = 'Высокая') AS [Среднее для высоких],
    
    (SELECT AVG(CAST(В.Количество_деталей AS FLOAT)) 
     FROM ВЫПОЛНЕНИЕ В 
     INNER JOIN ОПЕРАЦИИ О ON В.Наименование_операции = О.Наименование_операции
     WHERE О.Признак_сложности = 'Средняя') AS [Среднее для средних],
    
    (SELECT AVG(CAST(В.Количество_деталей AS FLOAT)) 
     FROM ВЫПОЛНЕНИЕ В 
     INNER JOIN ОПЕРАЦИИ О ON В.Наименование_операции = О.Наименование_операции
     WHERE О.Признак_сложности = 'Низкая') AS [Среднее для низких];
GO

-- Задание 7
SELECT 
    В.Наименование_операции AS [Операция],
    В.Количество_деталей AS [Количество],
    В.Дата AS [Дата],
    Р.Фамилия AS [Работник]
FROM ВЫПОЛНЕНИЕ В
INNER JOIN РАБОТНИКИ Р ON В.ID_работника = Р.ID_работника
WHERE В.Количество_деталей >= ALL (
    SELECT В2.Количество_деталей
    FROM ВЫПОЛНЕНИЕ В2
    INNER JOIN ОПЕРАЦИИ О2 ON В2.Наименование_операции = О2.Наименование_операции
    WHERE О2.Признак_сложности = 'Высокая'
)
ORDER BY В.Количество_деталей DESC;
GO

