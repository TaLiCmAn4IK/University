USE master;
GO

IF DB_ID('PVR_MyBase_1') IS NOT NULL
BEGIN
    ALTER DATABASE PVR_MyBase_1 SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE PVR_MyBase_1;
END
GO

CREATE DATABASE PVR_MyBase_1;
GO

USE PVR_MyBase_1;
GO

-- =============================================================
-- СОЗДАНИЕ ТАБЛИЦ
-- =============================================================

-- Справочник операций
CREATE TABLE ОПЕРАЦИИ
(
    Наименование_операции  NVARCHAR(100) CONSTRAINT ОПЕРАЦИИ_PK PRIMARY KEY,
    Признак_сложности      NVARCHAR(50)
);
GO

-- Работники
CREATE TABLE РАБОТНИКИ
(
    ID_работника  INT CONSTRAINT РАБОТНИКИ_PK PRIMARY KEY,
    Фамилия       NVARCHAR(50),
    Имя           NVARCHAR(50),
    Отчество      NVARCHAR(50),
    Адрес         NVARCHAR(100),
    Телефон       NVARCHAR(20),
    Стаж          INT DEFAULT 0
);
GO

-- Журнал выполнения операций
CREATE TABLE ВЫПОЛНЕНИЕ
(
    ID_выполнения          INT CONSTRAINT ВЫПОЛНЕНИЕ_PK PRIMARY KEY,
    Наименование_операции  NVARCHAR(100) CONSTRAINT ВЫПОЛНЕНИЕ_ОПЕРАЦИИ_FK
                           FOREIGN KEY REFERENCES ОПЕРАЦИИ(Наименование_операции),
    Количество_деталей     INT CONSTRAINT CK_Количество CHECK (Количество_деталей > 0),
    Дата                   DATE,
    ID_работника           INT CONSTRAINT ВЫПОЛНЕНИЕ_РАБОТНИКИ_FK
                           FOREIGN KEY REFERENCES РАБОТНИКИ(ID_работника)
);
GO

PRINT 'Таблицы базы PVR_MyBase_1 созданы';
GO

