SELECT PULPIT.PULPIT_NAME AS [Наименование кафедры]
FROM PULPIT
WHERE PULPIT.FACULTY IN (
    SELECT DISTINCT PROFESSION.FACULTY 
    FROM PROFESSION 
    WHERE PROFESSION.PROFESSION_NAME LIKE '%технологи%'
);

