SELECT 
    (SELECT AVG(CAST(NOTE AS FLOAT)) FROM PROGRESS WHERE SUBJECT = 'ОАиП') AS [Средний балл ОАиП],
    (SELECT AVG(CAST(NOTE AS FLOAT)) FROM PROGRESS WHERE SUBJECT = 'БД') AS [Средний балл БД],
    (SELECT AVG(CAST(NOTE AS FLOAT)) FROM PROGRESS WHERE SUBJECT = 'СУБД') AS [Средний балл СУБД];

