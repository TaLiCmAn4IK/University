SELECT FACULTY.FACULTY_NAME AS [Наименование факультета]
FROM FACULTY
WHERE  EXISTS (
    SELECT 1
    FROM PULPIT
    WHERE PULPIT.FACULTY = FACULTY.FACULTY
);

