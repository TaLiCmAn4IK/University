SELECT DISTINCT PULPIT.PULPIT_NAME AS [Наименование кафедры]
FROM PULPIT
INNER JOIN FACULTY ON PULPIT.FACULTY = FACULTY.FACULTY
INNER JOIN PROFESSION ON FACULTY.FACULTY = PROFESSION.FACULTY
WHERE PROFESSION.PROFESSION_NAME LIKE '%технологи%';

-- Задание 4
SELECT DISTINCT
    a1.AUDITORIUM_TYPE AS [Тип],
    a1.AUDITORIUM_CAPACITY AS [Вместимость]
FROM AUDITORIUM a1
WHERE a1.AUDITORIUM_CAPACITY = (
    SELECT TOP 1 a2.AUDITORIUM_CAPACITY
    FROM AUDITORIUM a2
    WHERE a2.AUDITORIUM_TYPE = a1.AUDITORIUM_TYPE
    ORDER BY a2.AUDITORIUM_CAPACITY DESC
)
ORDER BY a1.AUDITORIUM_CAPACITY DESC;

