SELECT 
    З.Наименование_товара AS [Товар],
    З.Цена_продажи AS [Цена продажи]
FROM Заказы З
WHERE З.Цена_продажи >= ALL (
    SELECT Цена_продажи 
    FROM Заказы 
    WHERE Наименование_товара LIKE 'с%'
);

