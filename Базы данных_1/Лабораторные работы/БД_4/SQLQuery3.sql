-- Задание 1.
SELECT v.ID_выполнения,
       v.Наименование_операции,
       o.Признак_сложности,
       v.Количество_деталей,
       v.Дата
FROM ВЫПОЛНЕНИЕ v
INNER JOIN ОПЕРАЦИИ o ON v.Наименование_операции = o.Наименование_операции;
GO

-- Задание 2.
SELECT v.ID_выполнения,
       v.Наименование_операции,
       o.Признак_сложности,
       v.Количество_деталей,
       v.Дата
FROM ВЫПОЛНЕНИЕ v
INNER JOIN ОПЕРАЦИИ o ON v.Наименование_операции = o.Наименование_операции
WHERE o.Признак_сложности LIKE N'%Высокая%';
GO

-- Задание 3.
SELECT r.Фамилия + ' ' + r.Имя + ' ' + ISNULL(r.Отчество, '') AS [ФИО работника],
       o.Наименование_операции,
       o.Признак_сложности,
       v.Количество_деталей,
       v.Дата,
       CASE 
           WHEN v.Количество_деталей <= 5 THEN 'Мало'
           WHEN v.Количество_деталей BETWEEN 6 AND 15 THEN 'Средне'
           ELSE 'Много'
       END AS [Объем работы]
FROM ВЫПОЛНЕНИЕ v
INNER JOIN РАБОТНИКИ r ON v.ID_работника = r.ID_работника
INNER JOIN ОПЕРАЦИИ o ON v.Наименование_операции = o.Наименование_операции
WHERE v.Количество_деталей > 5
ORDER BY v.Количество_деталей DESC;
GO

-- Задание 4.
SELECT o.Наименование_операции,
       o.Признак_сложности,
       ISNULL(CAST(v.Количество_деталей AS NVARCHAR(10)), 'не выполнялась') AS [Количество деталей],
       ISNULL(CONVERT(NVARCHAR(10), v.Дата, 104), '—') AS [Дата]
FROM ОПЕРАЦИИ o
LEFT OUTER JOIN ВЫПОЛНЕНИЕ v ON o.Наименование_операции = v.Наименование_операции;
GO

-- Задание 5.
SELECT o.Наименование_операции AS [Операция],
       'не выполнялась' AS [Статус]
FROM ОПЕРАЦИИ o
LEFT OUTER JOIN ВЫПОЛНЕНИЕ v ON o.Наименование_операции = v.Наименование_операции
WHERE v.Наименование_операции IS NULL;
GO

SELECT r.Фамилия + ' ' + r.Имя + ' ' + ISNULL(r.Отчество, '') AS [ФИО],
       'нет выполнений' AS [Статус]
FROM РАБОТНИКИ r
LEFT OUTER JOIN ВЫПОЛНЕНИЕ v ON r.ID_работника = v.ID_работника
WHERE v.ID_работника IS NULL;
GO

SELECT v.ID_выполнения,
       o.Наименование_операции,
       r.Фамилия + ' ' + r.Имя AS [Работник],
       v.Количество_деталей
FROM ВЫПОЛНЕНИЕ v
INNER JOIN ОПЕРАЦИИ o ON v.Наименование_операции = o.Наименование_операции
INNER JOIN РАБОТНИКИ r ON v.ID_работника = r.ID_работника;
GO

-- Задание 6.
SELECT r.Фамилия + ' ' + r.Имя AS [Работник],
       o.Наименование_операции AS [Операция]
FROM РАБОТНИКИ r
CROSS JOIN ОПЕРАЦИИ o
WHERE o.Признак_сложности = 'Высокая'
ORDER BY r.Фамилия, o.Наименование_операции;
GO