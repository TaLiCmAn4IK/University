DROP FUNCTION IF EXISTS dbo.FFACPUL;
GO

CREATE FUNCTION dbo.FFACPUL
(
    @f VARCHAR(20) = NULL,
    @p VARCHAR(20) = NULL
)
RETURNS TABLE
AS
RETURN
(
    SELECT F.FACULTY,
           F.FACULTY_NAME,
           P.PULPIT,
           P.PULPIT_NAME
    FROM FACULTY F
    LEFT JOIN PULPIT P ON F.FACULTY = P.FACULTY
    WHERE (@f IS NULL OR F.FACULTY = @f)
      AND (@p IS NULL OR P.PULPIT = @p)
);
GO

