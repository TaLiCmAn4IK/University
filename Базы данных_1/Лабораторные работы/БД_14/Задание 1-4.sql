DROP FUNCTION IF EXISTS dbo.FCTEACHER;
GO

CREATE FUNCTION dbo.FCTEACHER
(
    @p VARCHAR(20) = NULL
)
RETURNS INT
AS
BEGIN
    DECLARE @count INT;

    SELECT @count = COUNT(*)
    FROM TEACHER
    WHERE @p IS NULL OR PULPIT = @p;

    RETURN @count;
END;
GO

SELECT dbo.FCTEACHER(DEFAULT) AS Всего_преподавателей;
SELECT dbo.FCTEACHER('ИСиТ') AS Преподавателей_на_кафедре;
