CREATE TRIGGER dbo.TR_TEACHER
ON dbo.TEACHER
AFTER INSERT, DELETE, UPDATE
AS
BEGIN
    IF EXISTS (SELECT 1 FROM inserted) AND NOT EXISTS (SELECT 1 FROM deleted)
    BEGIN
        INSERT INTO dbo.TR_AUDIT (STMT, TRNAME, CC)
        SELECT 'INSERT',
               'TR_TEACHER',
               RTRIM(TEACHER) + N' ' + ISNULL(TEACHER_NAME, N'') + N' ' + RTRIM(ISNULL(PULPIT, ''))
        FROM inserted;
    END;

    IF NOT EXISTS (SELECT 1 FROM inserted) AND EXISTS (SELECT 1 FROM deleted)
    BEGIN
        INSERT INTO dbo.TR_AUDIT (STMT, TRNAME, CC)
        SELECT 'DELETE',
               'TR_TEACHER',
               RTRIM(TEACHER)
        FROM deleted;
    END;

    IF EXISTS (SELECT 1 FROM inserted) AND EXISTS (SELECT 1 FROM deleted)
    BEGIN
        INSERT INTO dbo.TR_AUDIT (STMT, TRNAME, CC)
        SELECT 'UPDATE',
               'TR_TEACHER',
               N'Было: ' + RTRIM(D.TEACHER) + N' ' + ISNULL(D.TEACHER_NAME, N'') + N' ' + RTRIM(ISNULL(D.PULPIT, '')) +
               N' Стало: ' + RTRIM(I.TEACHER) + N' ' + ISNULL(I.TEACHER_NAME, N'') + N' ' + RTRIM(ISNULL(I.PULPIT, ''))
        FROM inserted I
        INNER JOIN deleted D ON I.TEACHER = D.TEACHER;
    END;
END;
GO

