CREATE TRIGGER DDL_UNIVER_TABLES
ON DATABASE
FOR DDL_DATABASE_LEVEL_EVENTS
AS
BEGIN
    DECLARE @eventType NVARCHAR(100);
    DECLARE @objectName NVARCHAR(100);
    DECLARE @objectType NVARCHAR(100);

    SET @eventType = EVENTDATA().value('(/EVENT_INSTANCE/EventType)[1]', 'NVARCHAR(100)');
    SET @objectName = EVENTDATA().value('(/EVENT_INSTANCE/ObjectName)[1]', 'NVARCHAR(100)');
    SET @objectType = EVENTDATA().value('(/EVENT_INSTANCE/ObjectType)[1]', 'NVARCHAR(100)');

    PRINT N'Тип события: ' + ISNULL(@eventType, N'');
    PRINT N'Имя объекта: ' + ISNULL(@objectName, N'');
    PRINT N'Тип объекта: ' + ISNULL(@objectType, N'');

    IF @eventType IN ('CREATE_TABLE', 'DROP_TABLE')
    BEGIN
        PRINT N'Операция запрещена: создание и удаление таблиц запрещено';
        RAISERROR(N'Создание и удаление таблиц запрещено', 16, 1);
        ROLLBACK;
    END;
END;
GO

BEGIN TRY
    EXEC('CREATE TABLE dbo.TEST_DDL_15_CREATE (ID INT)');
